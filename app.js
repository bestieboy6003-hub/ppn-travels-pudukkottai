// Fare Calculator Logic
function initCalculator() {
  const vehicleSelect = document.getElementById('calc-vehicle');
  const distanceInput = document.getElementById('calc-distance');
  const daysInput = document.getElementById('calc-days');
  const tripTypeSelect = document.getElementById('calc-triptype');

  if (!vehicleSelect) return;

  // Populate vehicle dropdown
  vehicleSelect.innerHTML = vehicles.map(v => `<option value="${v.id}">${v.name} (₹${v.ratePerKm}/km)</option>`).join('');

  // Event Listeners for Live Calculation
  vehicleSelect.addEventListener('change', calculateFare);
  distanceInput.addEventListener('input', calculateFare);
  daysInput.addEventListener('input', calculateFare);
  tripTypeSelect.addEventListener('change', calculateFare);

  calculateFare();
}

function calculateFare() {
  const vehicleId = document.getElementById('calc-vehicle').value;
  const distance = parseFloat(document.getElementById('calc-distance').value) || 200;
  const days = parseInt(document.getElementById('calc-days').value) || 1;
  const tripType = document.getElementById('calc-triptype').value;

  const vehicle = vehicles.find(v => v.id === vehicleId) || vehicles[0];
  
  // Total KM calculation
  let effectiveKm = distance;
  if (tripType === 'round' && effectiveKm < days * 250) {
    effectiveKm = days * 250;
  }

  const kmCost = effectiveKm * vehicle.ratePerKm;
  const bataTotal = days * vehicle.bataPerDay;
  const totalFare = kmCost + bataTotal;

  document.getElementById('res-rate-km').innerText = `₹${vehicle.ratePerKm}`;
  document.getElementById('res-km-cost').innerText = `₹${kmCost.toLocaleString('en-IN')}`;
  document.getElementById('res-bata').innerText = `₹${bataTotal.toLocaleString('en-IN')}`;
  document.getElementById('res-total-fare').innerText = `₹${totalFare.toLocaleString('en-IN')}`;
}

